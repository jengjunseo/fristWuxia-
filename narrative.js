export function endingLetters(state) {
  const f = state.flags;
  const letters = [
    ['만복', '네 이름을 투숙객 장부 첫 줄에 적었다. 천하제일도 밥값은 내야 한다. 대신 곱빼기는 공짜다.'],
    ['도강', f.settledWithoutFight ? '네가 남긴 통행 약속은 아직 산길에 걸려 있소. 이번 겨울엔 한 수레도 잃지 않았소.' : '표국과 산채가 함께 첫 양곡 수레를 보냈소. 장부보다 서로의 얼굴을 먼저 확인하면서.'],
    ['청허', f.trainingStyle === 'footwork' ? '네가 비켜선 반 걸음만큼 남을 위한 자리가 생겼다. 이제 네 발로 걸어라.' : '검끝은 곧아졌고 네 마음은 날카로워지지 않았다. 그것이면 충분하다.']
  ];
  if ((state.trust.disciple || 0) > 0) letters.push(['소연', '다음엔 같이 차를 마시자! 이번에는 정말 소금을 안 넣었어. 아마도.']);
  if ((state.trust.performer || 0) > 0) letters.push(['아루', '네 이야기를 노래로 만들었어. 첫 소절은 배고픈 사람 이야기야. 사람들이 제일 좋아하더라.']);
  return letters;
}
